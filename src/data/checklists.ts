export function checksFor(type: PropertyType): CheckItem[] {
  return CHECKS.filter((c) => c.appliesTo.includes(type));
}

export function categoriesFor(type: PropertyType): Category[] {
  const present = new Set(checksFor(type).map((c) => c.cat));
  return CATEGORIES.filter((c) => present.has(c.id));
}

